"use client";

import { useEffect, useState } from "react";

interface StatItemProps {
  value: number;
  suffix?: string;
  label: string;
  icon: React.ReactNode;
}

function StatItem({ value, suffix = "", label, icon }: StatItemProps) {
  const [count, setCount] = useState(0);

  useEffect(() => {
    const duration = 2000;
    const steps = 60;
    const increment = value / steps;
    let current = 0;

    const timer = setInterval(() => {
      current += increment;
      if (current >= value) {
        setCount(value);
        clearInterval(timer);
      } else {
        setCount(Math.floor(current));
      }
    }, duration / steps);

    return () => clearInterval(timer);
  }, [value]);

  return (
    <div className="text-center">
      <div className="inline-flex items-center justify-center w-16 h-16 bg-forest/10 rounded-full mb-4 text-forest">
        {icon}
      </div>
      <div className="text-4xl sm:text-5xl font-bold text-charcoal mb-2">
        {count.toLocaleString("pt-BR")}
        {suffix}
      </div>
      <div className="text-muted font-medium">{label}</div>
    </div>
  );
}

